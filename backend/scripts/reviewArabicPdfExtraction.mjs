import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { proofreadArabicText, ARABIC_PROOFREADING_POLICY } from "@digital-leadership/shared";
import { manifest, catalogRoot } from "../dist/finquiz/catalog.js";
import { readAsset } from "../dist/finquiz/assetFiles.js";
import { academicPdfLayout } from "../dist/contentAutomation/pdfAcademicLayout.js";
const hash = value => createHash("sha256").update(value).digest("hex");
const data = JSON.parse(await readFile(new URL("extractedSources.json", catalogRoot), "utf8"));
const display = JSON.parse(await readFile(new URL("academicDisplaySources.json", catalogRoot), "utf8"));
const report = [];
for (const canonical of data.sources) {
  if (hash(canonical.text) !== canonical.textSha256) throw new Error("Changed grading transcript");
  const reading = display.sources.find(source => source.sha256 === canonical.sha256);
  const source = reading ?? canonical;
  if (hash(source.text) !== source.textSha256) throw new Error("Changed academic reading");
  const asset = Object.values(manifest.assets).find(asset => asset.sha256 === source.sha256 && !asset.bodyHtml);
  if (!asset) {
    if (source.sha256 !== "8b7cc1cca073fa98ceacc56750a067295894d1a53e8f63dae72ac01599921a67") throw new Error("Missing approved PDF");
    report.push({ assetId: null, privateUpload: true, fileId: "9c985ea6-c8f6-4fee-a67a-ef2bf91d234c", sha256: source.sha256, method: source.method, textSha256: source.textSha256, characters: source.text.length });
    continue;
  }
  const bytes = await readAsset(asset, catalogRoot);
  if (hash(bytes) !== source.sha256 || bytes.length !== asset.sizeBytes) throw new Error("Changed original PDF");
  let pageCount;
  if (reading) {
    const layout = await academicPdfLayout(bytes);
    if (!layout || hash(proofreadArabicText(layout.text).replace(/\n{3,}/gu, "\n\n").trim()) !== reading.textSha256) throw new Error("Reading no longer agrees with PDF characters");
    pageCount = layout.pageCount;
  }
  report.push({ assetId: asset.id, filename: asset.filename, sha256: source.sha256, method: reading ? "pdfjs-visual-line-layout" : "existing-reviewed-transcription", pageCount, textSha256: source.textSha256, characters: source.text.length });
}
// Only the review report is writable; grading transcripts and their keys are
// never regenerated by this display verification tool.
if (process.argv.includes("--write")) await writeFile(new URL("arabicSourceReview.json", catalogRoot), JSON.stringify({ policy: ARABIC_PROOFREADING_POLICY, sources: report }, null, 2) + "\n");
console.log(JSON.stringify({ reviewedFiles: report.length, independentlyReadFiles: report.filter(row => row.method === "pdfjs-visual-line-layout").length }));
